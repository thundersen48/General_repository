import numpy as np

# Заданные значения
p0 = 10  # начальное положение
v = 5    # начальная скорость
a = 2    # ускорение

# Создание массива значений времени от 1 до 10
t = np.arange(1, 11)

# Рассчет массива p по формуле p = p0 + v*t + a*t^2/2
def function():
    p = p0 + v*t + a*t**2/2
    return p

# Вывод результатов
print("Массив значений времени:")
print(t)
print("\nМассив значений, рассчитанных по формуле:")
print(function())
